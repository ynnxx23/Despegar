DROP FUNCTION IF EXISTS upsert_incidente(INT, INT, TEXT, TEXT, TEXT, TEXT, TEXT, INTERVAL, INT, TEXT, TEXT);
DROP FUNCTION IF EXISTS upsert_respuesta(INT, INT, TEXT);
DROP PROCEDURE IF EXISTS sembrar_demo();
DROP TABLE IF EXISTS respuestas CASCADE;
