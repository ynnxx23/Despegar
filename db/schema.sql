CREATE TABLE usuarios (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL CHECK (char_length(nombre) BETWEEN 2 AND 100),
  email VARCHAR(160) NOT NULL UNIQUE CHECK (email LIKE '%@%.%'),
  password_hash VARCHAR(255) NOT NULL,
  rol VARCHAR(10) NOT NULL DEFAULT 'viajero' CHECK (rol IN ('viajero', 'agente', 'admin')),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reservas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('vuelo', 'hotel')),
  codigo VARCHAR(20) NOT NULL,
  origen VARCHAR(80) NULL,
  destino VARCHAR(80) NULL,
  hotel VARCHAR(120) NULL,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'Confirmada',
  creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reservas_user ON reservas (user_id);

-- prioridad arranca NULL: el incidente entra sin triage y lo prioriza un agente.
CREATE TABLE incidentes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  reserva_id INT NULL REFERENCES reservas(id) ON DELETE SET NULL,
  tipo VARCHAR(20) NOT NULL CONSTRAINT incidentes_tipo_check CHECK (tipo IN (
    'Vuelo_cancelado', 'Vuelo_retrasado', 'Hotel_sin_reserva',
    'Equipaje', 'Cobro_indebido', 'Fraude', 'Otro')),
  titulo VARCHAR(120) NOT NULL CHECK (char_length(titulo) BETWEEN 5 AND 120),
  descripcion TEXT NOT NULL CHECK (char_length(descripcion) BETWEEN 10 AND 2000),
  prioridad VARCHAR(10) NULL CONSTRAINT incidentes_prioridad_check CHECK (prioridad IN ('Baja', 'Alta', 'Critica')),
  estado VARCHAR(10) NOT NULL DEFAULT 'Abierto' CONSTRAINT incidentes_estado_check CHECK (estado IN ('Abierto', 'EnGestion', 'Resuelto')),
  prioridad_sugerida VARCHAR(10) NULL,
  prioridad_motivo TEXT NULL,
  triado_por INT NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  triado_at TIMESTAMPTZ NULL,
  sla_vence_at TIMESTAMPTZ NULL,
  asignado_a INT NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_incidentes_user ON incidentes (user_id);
CREATE INDEX idx_incidentes_cola ON incidentes (estado, prioridad, creado_at);
CREATE INDEX idx_incidentes_asignado ON incidentes (asignado_a);
-- La cola ordena por SLA vencido: indice parcial para no penalizar los NULL.
CREATE INDEX idx_incidentes_sla ON incidentes (sla_vence_at) WHERE sla_vence_at IS NOT NULL;
CREATE INDEX idx_incidentes_tipo ON incidentes (tipo);

CREATE TABLE respuestas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incidente_id INT NOT NULL REFERENCES incidentes(id) ON DELETE CASCADE,
  autor_id INT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  mensaje TEXT NOT NULL CHECK (char_length(mensaje) BETWEEN 2 AND 2000),
  creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_respuestas_incidente ON respuestas (incidente_id);

CREATE TABLE incidente_eventos (
  id SERIAL PRIMARY KEY,
  incidente_id INT NOT NULL REFERENCES incidentes(id) ON DELETE CASCADE,
  actor_id INT NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  accion VARCHAR(30) NOT NULL,
  detalle TEXT NULL,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_eventos_incidente ON incidente_eventos (incidente_id, creado_at);

CREATE TABLE incidente_seguidores (
  incidente_id INT NOT NULL REFERENCES incidentes(id) ON DELETE CASCADE,
  agente_id INT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (incidente_id, agente_id)
);
CREATE INDEX idx_seguidores_agente ON incidente_seguidores (agente_id);

-- Solo se guarda el hash SHA-256 del refresh token: el token crudo viaja al cliente.
CREATE TABLE refresh_tokens (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  expira_at TIMESTAMPTZ NOT NULL,
  revocado_at TIMESTAMPTZ NULL,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_refresh_tokens_usuario ON refresh_tokens (usuario_id);

-- Historial de cambios de usuarios (altas, cambios de rol, activaciones).
-- Cada cambio hecho por un admin queda registrado con actor y valores previos.
CREATE TABLE usuarios_auditoria (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  actor_id INT NULL REFERENCES usuarios(id) ON DELETE SET NULL,
  accion VARCHAR(40) NOT NULL,
  campo VARCHAR(40) NULL,
  valor_anterior TEXT NULL,
  valor_nuevo TEXT NULL,
  detalle TEXT NULL,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_auditoria_usuario ON usuarios_auditoria (usuario_id, creado_at DESC);
CREATE INDEX idx_auditoria_actor ON usuarios_auditoria (actor_id, creado_at DESC);
CREATE INDEX idx_auditoria_fecha ON usuarios_auditoria (creado_at DESC);

-- 1. Función trigger: mantiene actualizado_at sin que PHP lo gestione.
CREATE OR REPLACE FUNCTION touch_actualizado_at() RETURNS trigger LANGUAGE plpgsql AS $trig$
BEGIN
  NEW.actualizado_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END; $trig$;

CREATE TRIGGER trg_incidentes_touch
  BEFORE UPDATE ON incidentes
  FOR EACH ROW EXECUTE FUNCTION touch_actualizado_at();

-- 2. Función trigger: un caso solo puede asignarse a un agente (o admin).
CREATE OR REPLACE FUNCTION chequear_agente_asignado() RETURNS trigger LANGUAGE plpgsql AS $chk$
BEGIN
  IF NEW.asignado_a IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM usuarios WHERE id = NEW.asignado_a AND rol IN ('agente', 'admin')
  ) THEN
    RAISE EXCEPTION 'El caso solo puede asignarse a un agente o admin' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END; $chk$;

CREATE TRIGGER trg_incidentes_agente
  BEFORE INSERT OR UPDATE OF asignado_a ON incidentes
  FOR EACH ROW EXECUTE FUNCTION chequear_agente_asignado();

-- 3. Función atómica: inserta la respuesta y marca EnGestion en la misma transacción.
-- Devuelve el id de la respuesta creada. Defensa en profundidad (PHP ya valida antes).
CREATE OR REPLACE FUNCTION crear_respuesta(p_incidente INT, p_autor INT, p_mensaje TEXT)
RETURNS INT LANGUAGE plpgsql AS $fun$
DECLARE v_id INT;
BEGIN
  IF char_length(p_mensaje) NOT BETWEEN 2 AND 2000 THEN
    RAISE EXCEPTION 'Mensaje inválido' USING ERRCODE = '22001';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM incidentes WHERE id = p_incidente) THEN
    RAISE EXCEPTION 'Incidente no encontrado' USING ERRCODE = 'P0002';
  END IF;
  INSERT INTO respuestas (incidente_id, autor_id, mensaje)
  VALUES (p_incidente, p_autor, p_mensaje) RETURNING id INTO v_id;
  UPDATE incidentes SET estado = 'EnGestion' WHERE id = p_incidente;
  RETURN v_id;
END; $fun$;

-- 4. Función de reporte: conteos para el panel del agente.
CREATE OR REPLACE FUNCTION resumen_cola()
RETURNS TABLE (estado VARCHAR, prioridad VARCHAR, total BIGINT)
LANGUAGE sql STABLE AS $rep$
  SELECT i.estado, i.prioridad, COUNT(*) FROM incidentes i GROUP BY 1, 2 ORDER BY 1, 2;
$rep$;

-- 5. Helpers idempotentes del seed (los usa sembrar_demo y las migraciones).
CREATE OR REPLACE FUNCTION upsert_usuario(p_nombre TEXT, p_email TEXT, p_hash TEXT, p_rol TEXT)
RETURNS INT LANGUAGE plpgsql AS $up$
DECLARE v_id INT;
BEGIN
  SELECT id INTO v_id FROM usuarios WHERE email = p_email;
  IF v_id IS NULL THEN
    INSERT INTO usuarios (nombre, email, password_hash, rol)
    VALUES (p_nombre, p_email, p_hash, p_rol) RETURNING id INTO v_id;
  END IF;
  RETURN v_id;
END; $up$;

CREATE OR REPLACE FUNCTION upsert_reserva(
  p_user INT, p_tipo TEXT, p_codigo TEXT, p_origen TEXT, p_destino TEXT,
  p_hotel TEXT, p_inicio DATE, p_fin DATE, p_estado TEXT
) RETURNS INT LANGUAGE plpgsql AS $upr$
DECLARE v_id INT;
BEGIN
  SELECT id INTO v_id FROM reservas WHERE codigo = p_codigo LIMIT 1;
  IF v_id IS NULL THEN
    INSERT INTO reservas (user_id, tipo, codigo, origen, destino, hotel, fecha_inicio, fecha_fin, estado)
    VALUES (p_user, p_tipo, p_codigo, p_origen, p_destino, p_hotel, p_inicio, p_fin, COALESCE(p_estado, 'Confirmada'))
    RETURNING id INTO v_id;
  END IF;
  RETURN v_id;
END; $upr$;

CREATE OR REPLACE FUNCTION upsert_incidente(
  p_user INT, p_reserva INT, p_tipo TEXT, p_titulo TEXT, p_desc TEXT,
  p_prioridad TEXT, p_estado TEXT, p_sla INTERVAL, p_asignado INT,
  p_sugerida TEXT, p_motivo TEXT
) RETURNS INT LANGUAGE plpgsql AS $upi$
DECLARE v_id INT;
BEGIN
  SELECT id INTO v_id FROM incidentes WHERE user_id = p_user AND titulo = p_titulo LIMIT 1;
  IF v_id IS NULL THEN
    INSERT INTO incidentes (
      user_id, reserva_id, tipo, titulo, descripcion, prioridad, estado,
      prioridad_sugerida, prioridad_motivo, triado_por, triado_at, sla_vence_at, asignado_a
    ) VALUES (
      p_user, p_reserva, p_tipo, p_titulo, p_desc, p_prioridad, p_estado,
      p_sugerida, p_motivo,
      CASE WHEN p_prioridad IS NULL THEN NULL ELSE p_asignado END,
      CASE WHEN p_prioridad IS NULL THEN NULL ELSE now() END,
      CASE WHEN p_sla IS NULL THEN NULL ELSE now() + p_sla END,
      p_asignado
    ) RETURNING id INTO v_id;
  END IF;
  RETURN v_id;
END; $upi$;

CREATE OR REPLACE FUNCTION upsert_respuesta(p_incidente INT, p_autor INT, p_mensaje TEXT)
RETURNS INT LANGUAGE plpgsql AS $ups$
DECLARE v_id INT;
BEGIN
  SELECT id INTO v_id FROM respuestas
   WHERE incidente_id = p_incidente AND autor_id = p_autor AND mensaje = p_mensaje LIMIT 1;
  IF v_id IS NULL THEN
    INSERT INTO respuestas (incidente_id, autor_id, mensaje) VALUES (p_incidente, p_autor, p_mensaje)
    RETURNING id INTO v_id;
  END IF;
  RETURN v_id;
END; $ups$;

