-- Migrate 04: refresh tokens (tabla nueva del schema v3).
-- Idempotente: se aplica sobre una base v3 que todavia no tenga la tabla.
BEGIN;

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  token_hash VARCHAR(64) NOT NULL UNIQUE,
  expira_at TIMESTAMPTZ NOT NULL,
  revocado_at TIMESTAMPTZ NULL,
  creado_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_usuario ON refresh_tokens (usuario_id);

-- Indice que el schema v3 agrega y las bases migradas todavia no tienen.
CREATE INDEX IF NOT EXISTS idx_incidentes_asignado ON incidentes (asignado_a);

COMMIT;
